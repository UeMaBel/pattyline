from copy import deepcopy
import os
from pathlib import Path
import tempfile
import unittest
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from unittest.mock import patch

from pattyline.broker import Broker, Transport, parse_content
from pattyline.common import Blocked, write_json
from pattyline.config import DEFAULTS
from pattyline.runtime import validate_result
from tests.support import FakeSandbox


class FakeTransport:
    def __init__(self, responses):
        self.responses = list(responses)
        self.history = []

    def complete(self, route, history, output_schema, timeout, **options):
        self.history.append(list(history))
        return self.responses.pop(0)


def response(calls=None, result=None):
    return {"calls": calls or [], "result": result, "message": [], "session": "provider-session", "usage": "unknown"}


class BrokerTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.values = deepcopy(DEFAULTS)
        self.values["runtime"]["cloud_model"] = "test-cloud"
        self.values["runtime"]["local_model"] = "test-local"

    def broker(self, transport, sandbox=None):
        instance = Broker(self.temp.name, self.values, sandbox or FakeSandbox(), transport)
        # Test only direct injection; production signatures cannot be generated by fixtures.
        instance.prerequisites = lambda route, stage="implementation": []
        instance.readiness = lambda route, stage: []
        return instance

    def test_tool_requests_execute_only_in_boundary_and_review_is_readonly(self):
        sandbox = FakeSandbox()
        tool = {"id": "call-1", "name": "run_command", "arguments": {"argv": ["python", "-c", "print('evidence')"], "cwd": ".", "timeout": 3}}
        final = {"verdict": "approved", "findings": [], "acceptance_evidence": {"criterion": "actual check"}}
        transport = FakeTransport([response([tool]), response(result=final)])
        result = self.broker(transport, sandbox).execute("review", "cloud", Path(self.temp.name) / "worktree", {"protected_paths": ["spec.md"]})
        validate_result(result, "review")
        self.assertTrue(sandbox.calls[0]["readonly"])
        self.assertEqual(sandbox.calls[0]["protected"], ["spec.md"])
        self.assertEqual(transport.history[1][-1]["type"], "function_call_output")
        self.assertEqual(len(result["tools"]), 1)

    def test_unknown_tool_or_escaped_cwd_cannot_execute(self):
        sandbox = FakeSandbox()
        tool = {"id": "call", "name": "host_shell", "arguments": {"argv": ["dangerous"], "cwd": ".", "timeout": 1}}
        with self.assertRaisesRegex(Blocked, "Unknown"):
            self.broker(FakeTransport([response([tool])]), sandbox).execute("implementation", "cloud", "unused", {})
        tool["name"] = "run_command"
        tool["arguments"]["cwd"] = "../primary"
        with self.assertRaisesRegex(Blocked, "relative"):
            self.broker(FakeTransport([response([tool])]), sandbox).execute("implementation", "cloud", "unused", {})
        self.assertEqual(sandbox.calls, [])

    def test_fixtures_cannot_produce_real_capability_evidence(self):
        with self.assertRaisesRegex(Blocked, "Test adapters"):
            Broker(self.temp.name, self.values, FakeSandbox(), FakeTransport([])).probe("cloud", "implementation")

    def test_unsigned_pass_claims_cannot_enable_dispatch(self):
        root = Path(self.temp.name)
        write_json(root / ".pattyline/evidence/broker-cloud-implementation.json", {"binding": "invented", "outcome": "passed", "signature": "fake"})
        broker = Broker(root, self.values, FakeSandbox())
        broker.prerequisites = lambda route, stage="implementation": []
        self.assertIn("Missing trusted", broker.readiness()[0])

    def test_malformed_results_and_unbounded_tool_calls_fail_closed(self):
        with self.assertRaisesRegex(Blocked, "Malformed"):
            parse_content("success without JSON")
        self.values["runtime"]["max_tool_calls"] = 1
        tool = {"id": "call", "name": "run_command", "arguments": {"argv": ["test"], "cwd": ".", "timeout": 1}}
        transport = FakeTransport([response([tool]), response([tool])])
        with self.assertRaisesRegex(Blocked, "budget exhausted"):
            self.broker(transport).execute("implementation", "cloud", "worktree", {})

    def test_cancellation_stops_before_provider_request(self):
        transport = FakeTransport([])
        with self.assertRaisesRegex(Blocked, "cancelled"):
            self.broker(transport).execute("implementation", "cloud", "worktree", {}, cancelled=lambda: True)
        self.assertEqual(transport.history, [])

    def test_context_limit_preserves_handoff_before_provider_dispatch(self):
        self.values["runtime"]["max_context_bytes"] = 100
        transport = FakeTransport([])
        with self.assertRaisesRegex(Blocked, "full decisions/progress retained"):
            self.broker(transport).execute("implementation", "cloud", "worktree", {"decisions": ["preserve this unresolved product choice"]})
        self.assertEqual(transport.history, [])
        logs = list((Path(self.temp.name) / ".pattyline/transcripts").glob("*.json"))
        self.assertEqual(len(logs), 1)
        self.assertIn("preserve this unresolved product choice", logs[0].read_text())

    def test_actual_http_leaf_process_is_cancellable_without_replay(self):
        entered, release = threading.Event(), threading.Event()
        requests = []
        class Handler(BaseHTTPRequestHandler):
            def do_POST(self):
                requests.append(self.rfile.read(int(self.headers["Content-Length"])))
                entered.set()
                release.wait(5)
            def log_message(self, *args):
                pass
        server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        records = []
        try:
            with self.assertRaisesRegex(Blocked, "cancelled/deadline"):
                Transport(self.values).request(f"http://127.0.0.1:{server.server_port}/fake-provider", {"prompt": "test only"}, {"Content-Type": "application/json"}, 5,
                    cancelled=lambda: entered.is_set(), grace=1, on_stop=lambda record: records.append(record))
            self.assertEqual(len(requests), 1)
            self.assertEqual(records[0]["mechanism"], "provider-transport")
            self.assertTrue(records[0]["trusted_leaf"])
        finally:
            release.set()
            server.shutdown()
            server.server_close()
